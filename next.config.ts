import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  reactStrictMode: true,

  images: {
    remotePatterns: [
      {
        protocol: "https",
        hostname: "*.supabase.co",
        pathname: "/storage/v1/object/public/**",
      },
    ],
    formats: ["image/avif", "image/webp"],
  },

  experimental: {
    // Enables React Compiler once stable in the toolchain.
    // reactCompiler: true,
  },

  async headers() {
    // Content-Security-Policy: intentionally uses 'unsafe-inline' for
    // script/style rather than a nonce-based strict policy. A nonce-based
    // CSP is stronger but requires generating a per-request nonce in
    // middleware and threading it through every <Script>/inline style,
    // which risks silently breaking Next's own hydration scripts and
    // Tailwind's inline styles without live testing against a real
    // deployment. This is the pragmatic middle ground: it still blocks
    // the most common attack (loading a malicious script/object from an
    // arbitrary third-party origin) while not risking breakage.
    const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval' https://va.vercel-scripts.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://*.supabase.co",
  "font-src 'self' data:",
  "connect-src 'self' https://*.supabase.co https://vitals.vercel-insights.com https://va.vercel-scripts.com",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
          { key: "Content-Security-Policy", value: csp },
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains; preload",
          },
        ],
      },
    ];
  },

  async redirects() {
    return [];
  },
};

export default nextConfig;
